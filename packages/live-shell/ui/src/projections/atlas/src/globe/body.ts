// The body you build (manual §17.2 "Build a planet"; T-WORLDS §5 W3, reopened by T-PROCEDURAL-BODY): the owner's record read, and the pictures and the land
// it draws, by the generator the record names. This module is the one place the rest of the shell reaches the generator: it parses the record, and every
// picture and every question of the land is answered by the generator of the record's version: 1 by globe/bodyLegacy.ts (the World design's value noise, kept
// exactly as it drew), 2 and later by globe/bodyV2.ts. A body built by version 1 keeps drawing as version 1; its next change (any dial, a reroll) rebuilds it as
// version 2 (atlas/body/worldBody.ts changedBody).
//
// The record is the owner's: `aikit.world-body/v1` on a register's root space (ai-kit knowledge_wiki_facts.rs WorldBody), read through the kernel
// (`world_body_read`, kernel construction.rs read_body). Nothing here holds or invents body state, and nothing here is random: the same record, look and time
// give the same body, byte for byte, in a worker or on the main thread. A reroll is the owner's write of a new seed (`nextSeed` names it from the record; the
// owner stores it).
//
// Pure TypeScript with no DOM and no three.js, so it runs in a worker.
import * as legacy from './bodyLegacy'
import * as current from './bodyV2'
import {weatherShift as shiftOf} from './bodyWeather'

export const WORLD_BODY_EXTENSION = 'aikit.world-body/v1'
export const WORLD_BODY_GENERATOR = 'fbm-sphere'
/** The generator version this module draws (the record names the version it was built for; version 1 is drawn by the legacy module). */
export const WORLD_BODY_GENERATOR_VERSION = 2
/** The widths the globe is given a body at: a small first picture at once, then the small-GPU base, then the capable-GPU base (each 256 × 2^k, so the tile level a
 * base is denser than, tileLevelFor, is a whole level). */
export const BODY_WIDTHS = {first: 256, lo: 2048, hi: 4096} as const
/** How a body is drawn, beside what it is (the owner's record): a reading computed from the world's own readings (system/maturity.ts), held nowhere, written
 * nowhere. `barren` takes a body toward a grey, airless, dry moon: 0 lived in (the default), 1 a barely shaped moon; values outside are held to the range. */
export interface BodyLook {
  readonly barren?: number
}
export const COASTS = ['smooth', 'fjord', 'archipelago'] as const
export type Coast = (typeof COASTS)[number]
export const CONTINENTS_RANGE = {min: 0.6, max: 3.6} as const
export const TILT_RANGE = {min: 0, max: 45} as const

/** `aikit.world-body/v1`, as the owner validates it (knowledge_wiki_facts.rs WorldBody::validate). */
export interface WorldBodyRecord {
  readonly body_ref: string
  readonly seed: number
  readonly generator: {readonly id: string; readonly version: number}
  readonly landmass: {readonly sea_level: number; readonly continents: number; readonly relief: number; readonly coast: Coast}
  readonly climate: {readonly warmth: number; readonly moisture: number; readonly ice_caps: number}
  readonly sky: {readonly atmosphere: number; readonly clouds: number; readonly axial_tilt_deg: number}
  readonly landing?: {readonly on_ref: string; readonly lat: number; readonly lon: number}
}

const isObject = (value: unknown): value is Record<string, unknown> => !!value && typeof value === 'object' && !Array.isArray(value)
const inRange = (value: unknown, min: number, max: number): value is number => typeof value === 'number' && Number.isFinite(value) && value >= min && value <= max

/** The record, or the reason it is not one, in the owner's terms. The shell reads the owner's record; it never repairs one. */
export function parseWorldBody(value: unknown): WorldBodyRecord | {readonly refused: string} {
  if (!isObject(value)) return {refused: 'the world body is not a record'}
  const {body_ref, seed, generator, landmass, climate, sky, landing} = value
  if (typeof body_ref !== 'string' || !body_ref.trim()) return {refused: 'the world body names no body reference'}
  if (!Number.isInteger(seed) || (seed as number) < 0 || (seed as number) > 0xffffffff) return {refused: 'the seed is a whole number from 0 to 4294967295'}
  if (!isObject(generator) || generator.id !== WORLD_BODY_GENERATOR || !Number.isInteger(generator.version) || (generator.version as number) < 1) {
    return {refused: `the body is generated by ${WORLD_BODY_GENERATOR}, version 1 to ${WORLD_BODY_GENERATOR_VERSION}`}
  }
  if ((generator.version as number) > WORLD_BODY_GENERATOR_VERSION) {
    return {refused: `the body was built by a newer generator (${WORLD_BODY_GENERATOR} version ${generator.version}) than this shell draws (version ${WORLD_BODY_GENERATOR_VERSION}); update the shell to see it`}
  }
  if (!isObject(landmass) || !isObject(climate) || !isObject(sky)) return {refused: 'the world body lacks its landmass, climate or sky'}
  const unit: [string, unknown][] = [['sea level', landmass.sea_level], ['relief', landmass.relief], ['warmth', climate.warmth], ['moisture', climate.moisture],
    ['ice caps', climate.ice_caps], ['atmosphere', sky.atmosphere], ['clouds', sky.clouds]]
  for (const [what, x] of unit) if (!inRange(x, 0, 1)) return {refused: `${what} runs from 0 to 1`}
  if (!inRange(landmass.continents, CONTINENTS_RANGE.min, CONTINENTS_RANGE.max)) return {refused: `continents runs from ${CONTINENTS_RANGE.min} to ${CONTINENTS_RANGE.max}`}
  if (!(COASTS as readonly unknown[]).includes(landmass.coast)) return {refused: `the coast is ${COASTS.join(', ')}`}
  if (!inRange(sky.axial_tilt_deg, TILT_RANGE.min, TILT_RANGE.max)) return {refused: `the axial tilt runs from ${TILT_RANGE.min} to ${TILT_RANGE.max} degrees`}
  if (landing !== undefined && landing !== null) {
    if (!isObject(landing) || typeof landing.on_ref !== 'string' || !inRange(landing.lat, -90, 90) || !inRange(landing.lon, -180, 180)) {
      return {refused: 'the landing names the body it lands on and a latitude and longitude on it'}
    }
  }
  return value as unknown as WorldBodyRecord
}

export const isWorldBody = (value: WorldBodyRecord | {readonly refused: string}): value is WorldBodyRecord => !('refused' in value)

const D2R = Math.PI / 180

/** The look as the generator reads it: barren held to 0–1, an absent or non-numeric one the lived-in default. */
export const barrenOf = (look?: BodyLook | null): number => {
  const b = look?.barren
  return typeof b === 'number' && Number.isFinite(b) ? (b < 0 ? 0 : b > 1 ? 1 : b) : 0
}

/** The point on the unit sphere at a latitude and longitude (the design's `unit`): y is the axis, north up. */
export function unitOf(lat: number, lon: number): {x: number; y: number; z: number} {
  return {x: Math.cos(lat * D2R) * Math.cos(lon * D2R), y: Math.sin(lat * D2R), z: Math.cos(lat * D2R) * Math.sin(lon * D2R)}
}

// ── the generator of the record's version ─────────────────────────────────────────────────────────────────────────────────

const legacyOf = (record: WorldBodyRecord): boolean => record.generator.version === 1

/** Height at a point of the sphere, 0–1: the field the Place tool, the picture and a tile are one function of. */
export function heightAt(record: WorldBodyRecord, x: number, y: number, z: number): number {
  return legacyOf(record) ? legacy.heightAt(record, x, y, z) : current.heightAt(record, x, y, z)
}

/** The height the sea stands at: a point is land where `heightAt` is above it. */
export const seaHeight = (record: WorldBodyRecord): number => (legacyOf(record) ? legacy.seaHeight(record) : current.seaHeight(record))
export const isLand = (record: WorldBodyRecord, height: number): boolean => height > seaHeight(record)

// ── the shore ─────────────────────────────────────────────────────────────────────────────────────────────────────────

/** Where a location is drawn on this body: its own point where that is land, else the nearest shore found within 20° (rings of
 * 2°, every 30°, the design's drawnAt), said so. The location's coordinate is never changed: this is drawing only (placeTool.ts:
 * the atlas never writes a coordinate). `found` is false where no land stands within 20°: the location is then drawn at its own
 * point, on the sea, and still said to be off its shore. */
export function shoreOf(record: WorldBodyRecord, lat: number, lon: number): {lat: number; lon: number; shore: boolean; found: boolean} {
  const here = unitOf(lat, lon)
  if (isLand(record, heightAt(record, here.x, here.y, here.z))) return {lat, lon, shore: false, found: true}
  for (let r = 2; r <= 20; r += 2) {
    for (let a = 0; a < 360; a += 30) {
      const la = Math.max(-89, Math.min(89, lat + r * Math.sin(a * D2R))), lo = lon + r * Math.cos(a * D2R), q = unitOf(la, lo)
      if (isLand(record, heightAt(record, q.x, q.y, q.z))) return {lat: la, lon: ((lo + 540) % 360) - 180, shore: true, found: true}
    }
  }
  return {lat, lon, shore: true, found: false}
}

/** An equirect RGBA image in the Earth imagery's convention: row 0 is the north pole's edge (lat +90), column 0 is longitude −180,
 * the last column just short of +180. */
export interface BodyImage {
  readonly width: number
  readonly height: number
  readonly data: Uint8ClampedArray
}

/** The degrees of longitude the body's cloud mask is carried at a latitude at a time (ms): the wind differs by latitude band, smoothly, and is a pure function of the
 * record's seed, the latitude and the time. A body of generator version 1 has no weather. */
export const weatherShift = (record: WorldBodyRecord, latDeg: number, timeMs: number): number => shiftOf(record, latDeg, timeMs)

// ── the pictures ──────────────────────────────────────────────────────────────────────────────────────────────────────────

/** The body as an equirect image, `width` × `width / 2`. Deterministic: the same record, width and look give the same bytes. */
export function bodyImage(record: WorldBodyRecord, width = 1024, look?: BodyLook): BodyImage {
  return legacyOf(record) ? legacy.bodyImage(record, width) : current.bodyImage(record, width, look)
}

/** How much of the body is land, 0–1, on the image's own cells weighted by their area (a reading for the device, not a setting). */
export function landShare(record: WorldBodyRecord, width = 128): number {
  return legacyOf(record) ? legacy.landShare(record, width) : current.landShare(record, width)
}

/** The cloud cover as an equirect mask in the body image's convention (row 0 the north edge, column 0 longitude −180): its red, green and blue are the cover
 * 0–255, alpha 255. `width` × `width / 2`. Deterministic, and empty (all 0) when the record asks for no cloud or the look is barren. */
export function cloudImage(record: WorldBodyRecord, width = 512, look?: BodyLook): BodyImage {
  return legacyOf(record) ? legacy.cloudImage(record, width) : current.cloudImage(record, width, look)
}

export type {CloudPart, CloudRegion} from './bodyV2'

/** The sky over a region of a body of generator version 2 as the analytic field has it, `part` of an `n` by `n` window (see bodyV2.ts cloudWindow): the opacity as the mask's own channels,
 * row 0 the north edge, the weather at `timeMs`. A body of version 1 has no weather and no window: it is empty. */
export function cloudWindow(record: WorldBodyRecord, region: current.CloudRegion, n: number, timeMs?: number | null, look?: BodyLook, part?: current.CloudPart): BodyImage {
  if (legacyOf(record)) { const w = part?.w ?? n, h = part?.h ?? n, data = new Uint8ClampedArray(w * h * 4); for (let k = 0; k < w * h; k++) data[k * 4 + 3] = 255; return {width: w, height: h, data} }
  return current.cloudWindow(record, region, n, timeMs, look, part)
}

/** How thick the body's air shows, as the globe's atmosphere takes it: 1 is the Earth's own (the World device's default 60 %), 0 none; a barren look thins it to 0. */
export const airOf = (record: WorldBodyRecord, look?: BodyLook): number => (legacyOf(record) ? legacy.airOf(record) : current.airOf(record, look))

/** The body seen whole as a small disc, `size` × `size` RGBA (transparent outside it), at the occasion `timeMs` (the weather of that moment; absent or null, the
 * weather's own zero: a generator has no clock, so a caller that means Now gives it). For a picture beside your planet, not for the globe. Deterministic. */
export function bodyDisc(record: WorldBodyRecord, size = 48, look?: BodyLook, timeMs?: number | null): BodyImage {
  return legacyOf(record) ? legacy.bodyDisc(record, size) : current.bodyDisc(record, size, look, timeMs)
}

// ── the reroll ────────────────────────────────────────────────────────────────────────────────────────────────────────

/** The seed a reroll asks the owner for: named from the record and the revision it was read at, so the same press on the same
 * reading asks for the same seed, and never the seed it already has. Nothing here is random. */
export function nextSeed(record: WorldBodyRecord, revision: number): number {
  let h = 0x811c9dc5
  const text = `${record.body_ref}|${record.seed}|${revision}`
  for (let i = 0; i < text.length; i++) { h ^= text.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0 }
  h ^= h >>> 16; h = Math.imul(h, 0x7feb352d) >>> 0; h ^= h >>> 15; h = Math.imul(h, 0x846ca68b) >>> 0; h ^= h >>> 16
  const seed = h >>> 0
  return seed === record.seed ? (seed + 1) >>> 0 : seed
}

/** The Earth's own obliquity, degrees: the scene's frame is the Earth's, so the Sun's declination there carries it. */
export const EARTH_OBLIQUITY_DEG = 23.4393

/** The Sun's direction as the body's own tilt casts it: the same hour (its direction about the axis is kept), at the declination the
 * body's axial tilt gives at the Sun's ecliptic longitude (sin δ = sin τ · sin λ), in place of the Earth's. A body tilted as the Earth
 * is lit as the Earth is; an upright body has no seasons; a body tilted further has deeper ones. Pure: `sun` is a unit vector in the
 * scene's axes (y the axis). */
export function bodySunDir(sun: {x: number; y: number; z: number}, sunLongitudeDeg: number, tiltDeg: number): {x: number; y: number; z: number} {
  const decl = Math.asin(Math.max(-1, Math.min(1, Math.sin(tiltDeg * D2R) * Math.sin(sunLongitudeDeg * D2R))))
  const flat = Math.hypot(sun.x, sun.z)
  if (flat < 1e-9) return {x: Math.cos(decl), y: Math.sin(decl), z: 0}
  const k = Math.cos(decl) / flat
  return {x: sun.x * k, y: Math.sin(decl), z: sun.z * k}
}

// ── a location's name, suggested from the seed (manual §17.2: "The World suggests a name from the seed. Keep it or type your own") ──

const ONSETS = ['b', 'd', 'f', 'g', 'h', 'k', 'l', 'm', 'n', 'r', 's', 't', 'v', 'th', 'sh', 'br', 'tr', 'gl']
const VOWELS = ['a', 'e', 'i', 'o', 'u', 'ae', 'ei', 'ou']
const CODAS = ['', '', 'n', 'r', 's', 'l', 'th', 'm']

/** A name for a spot of the body, from the body's seed and the spot (to a tenth of a degree): the same spot of the same body is always
 * offered the same name. A suggestion only: the person keeps it or types their own, and it is written only with the place. Pure. */
export function suggestName(record: Pick<WorldBodyRecord, 'seed'>, lat: number, lon: number): string {
  let h = 0x811c9dc5
  const text = `${record.seed}|${lat.toFixed(1)}|${lon.toFixed(1)}`
  for (let i = 0; i < text.length; i++) { h ^= text.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0 }
  const pick = <T,>(list: readonly T[]): T => { h = Math.imul(h ^ (h >>> 15), 0x2c1b3c6d) >>> 0; return list[h % list.length]! }
  const syllables = 2 + (h % 2)
  let name = ''
  for (let s = 0; s < syllables; s++) name += pick(ONSETS) + pick(VOWELS) + (s === syllables - 1 ? pick(CODAS) : '')
  return name[0]!.toUpperCase() + name.slice(1)
}


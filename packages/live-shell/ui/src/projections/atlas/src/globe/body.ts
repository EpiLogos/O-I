// The body you build (manual §17.2 "Build a planet"; T-WORLDS §5 W3): a pure generator from the owner's record to the equirect
// texture the Earth's seam takes (globe/earth.ts Earth's base texture, which loadBaseLo/loadBaseHi fill for the Earth), and the
// shore a location is drawn on where its own point is sea.
//
// The record is the owner's: `aikit.world-body/v1` on a register's root space (ai-kit knowledge_wiki_facts.rs WorldBody), read
// through the kernel (`world_body_read`, kernel construction.rs read_body). Nothing here holds or invents body state, and nothing
// here is random: the same record gives the same body, byte for byte, in a worker or on the main thread. A reroll is the owner's
// write of a new seed (`nextSeed` names it from the record; the owner stores it).
//
// Ported, not recreated: the noise, the height and the land test are the World design's own preview
// (inhabitants/catalogue/panels/atlas-earth__globe-engine.tsx:512-542 hash3, noise3, fbm, heightAt, isLand; :548-556 drawnAt), so the
// Body page's preview and the globe draw the same land. The colours carry the cues EARTH_FRAG grades (globe/shaders.ts EARTH_COMMON
// waterOf: sea is blue well above red; the bathymetry shelf is the sea's luma; land tone is luma with its relief shading baked in;
// ice is white), the way NASA Blue Marble carries them for the Earth.
//
// Pure TypeScript with no DOM and no three.js, so it runs in a worker.

export const WORLD_BODY_EXTENSION = 'aikit.world-body/v1'
export const WORLD_BODY_GENERATOR = 'fbm-sphere'
/** The generator version this module draws (the record names the version it was built for). */
export const WORLD_BODY_GENERATOR_VERSION = 1
export const COASTS = ['smooth', 'fjord', 'archipelago'] as const
export type Coast = (typeof COASTS)[number]
export const CONTINENTS_RANGE = {min: 0.6, max: 3.6} as const
export const TILT_RANGE = {min: 0, max: 45} as const

/** `aikit.world-body/v1`, as the owner validates it (knowledge_wiki_facts.rs WorldBody::validate). */
export interface WorldBodyRecord {
  readonly body_ref: string
  readonly seed: number
  readonly generator: {readonly id: string; readonly version: number}
  readonly landmass: {readonly sea_level: number; readonly continents: number; readonly relief: number; readonly coast: Coast}
  readonly climate: {readonly warmth: number; readonly moisture: number; readonly ice_caps: number}
  readonly sky: {readonly atmosphere: number; readonly clouds: number; readonly axial_tilt_deg: number}
  readonly landing?: {readonly on_ref: string; readonly lat: number; readonly lon: number}
}

const isObject = (value: unknown): value is Record<string, unknown> => !!value && typeof value === 'object' && !Array.isArray(value)
const inRange = (value: unknown, min: number, max: number): value is number => typeof value === 'number' && Number.isFinite(value) && value >= min && value <= max

/** The record, or the reason it is not one, in the owner's terms. The shell reads the owner's record; it never repairs one. */
export function parseWorldBody(value: unknown): WorldBodyRecord | {readonly refused: string} {
  if (!isObject(value)) return {refused: 'the world body is not a record'}
  const {body_ref, seed, generator, landmass, climate, sky, landing} = value
  if (typeof body_ref !== 'string' || !body_ref.trim()) return {refused: 'the world body names no body reference'}
  if (!Number.isInteger(seed) || (seed as number) < 0 || (seed as number) > 0xffffffff) return {refused: 'the seed is a whole number from 0 to 4294967295'}
  if (!isObject(generator) || generator.id !== WORLD_BODY_GENERATOR || !Number.isInteger(generator.version) || (generator.version as number) < 1) {
    return {refused: `the body is generated by ${WORLD_BODY_GENERATOR}, version 1 or later`}
  }
  if (!isObject(landmass) || !isObject(climate) || !isObject(sky)) return {refused: 'the world body lacks its landmass, climate or sky'}
  const unit: [string, unknown][] = [['sea level', landmass.sea_level], ['relief', landmass.relief], ['warmth', climate.warmth], ['moisture', climate.moisture],
    ['ice caps', climate.ice_caps], ['atmosphere', sky.atmosphere], ['clouds', sky.clouds]]
  for (const [what, x] of unit) if (!inRange(x, 0, 1)) return {refused: `${what} runs from 0 to 1`}
  if (!inRange(landmass.continents, CONTINENTS_RANGE.min, CONTINENTS_RANGE.max)) return {refused: `continents runs from ${CONTINENTS_RANGE.min} to ${CONTINENTS_RANGE.max}`}
  if (!(COASTS as readonly unknown[]).includes(landmass.coast)) return {refused: `the coast is ${COASTS.join(', ')}`}
  if (!inRange(sky.axial_tilt_deg, TILT_RANGE.min, TILT_RANGE.max)) return {refused: `the axial tilt runs from ${TILT_RANGE.min} to ${TILT_RANGE.max} degrees`}
  if (landing !== undefined && landing !== null) {
    if (!isObject(landing) || typeof landing.on_ref !== 'string' || !inRange(landing.lat, -90, 90) || !inRange(landing.lon, -180, 180)) {
      return {refused: 'the landing names the body it lands on and a latitude and longitude on it'}
    }
  }
  return value as unknown as WorldBodyRecord
}

export const isWorldBody = (value: WorldBodyRecord | {readonly refused: string}): value is WorldBodyRecord => !('refused' in value)

// ── the noise: the design's own value noise on the unit sphere, seeded ────────────────────────────────────────────────

/** A hash at a lattice corner (the design's hash3). */
function hash3(seed: number, x: number, y: number, z: number): number {
  let h = (seed ^ Math.imul(x, 374761393) ^ Math.imul(y, 668265263) ^ Math.imul(z, 2147483647)) >>> 0
  h = Math.imul(h ^ (h >>> 13), 1274126177) >>> 0
  return ((h ^ (h >>> 16)) >>> 0) / 4294967295
}
/** Value noise, smoothly blended between lattice corners (the design's noise3, the same arithmetic in the same order, unrolled so a
 * full-size body does not allocate a closure per sample). */
function noise3(seed: number, x: number, y: number, z: number): number {
  const xi = Math.floor(x), yi = Math.floor(y), zi = Math.floor(z)
  const fx = x - xi, fy = y - yi, fz = z - zi
  const u = fx * fx * (3 - 2 * fx), w = fy * fy * (3 - 2 * fy), t = fz * fz * (3 - 2 * fz)
  const c000 = hash3(seed, xi, yi, zi), c100 = hash3(seed, xi + 1, yi, zi), c010 = hash3(seed, xi, yi + 1, zi), c110 = hash3(seed, xi + 1, yi + 1, zi)
  const c001 = hash3(seed, xi, yi, zi + 1), c101 = hash3(seed, xi + 1, yi, zi + 1), c011 = hash3(seed, xi, yi + 1, zi + 1), c111 = hash3(seed, xi + 1, yi + 1, zi + 1)
  const a0 = c000 + (c100 - c000) * u, b0 = c010 + (c110 - c010) * u, a1 = c001 + (c101 - c001) * u, b1 = c011 + (c111 - c011) * u
  const near = a0 + (b0 - a0) * w, far = a1 + (b1 - a1) * w
  return near + (far - near) * t
}
/** Fractal noise: octaves of value noise, each finer and weaker by `rough` (the design's fbm). */
function fbm(seed: number, x: number, y: number, z: number, octaves: number, rough: number): number {
  let sum = 0, amp = 1, norm = 0, f = 1
  for (let o = 0; o < octaves; o++) { sum += amp * noise3(seed + o * 101, x * f, y * f, z * f); norm += amp; amp *= rough; f *= 2.02 }
  return sum / norm
}

const clamp01 = (x: number) => (x < 0 ? 0 : x > 1 ? 1 : x)
const D2R = Math.PI / 180

/** The point on the unit sphere at a latitude and longitude (the design's `unit`): y is the axis, north up. */
export function unitOf(lat: number, lon: number): {x: number; y: number; z: number} {
  return {x: Math.cos(lat * D2R) * Math.cos(lon * D2R), y: Math.sin(lat * D2R), z: Math.cos(lat * D2R) * Math.sin(lon * D2R)}
}

/** Height at a point of the sphere, 0–1 (the design's heightAt). */
export function heightAt(record: WorldBodyRecord, x: number, y: number, z: number): number {
  const {continents, relief, coast} = record.landmass
  const k = continents * 1.1, detail = coast === 'fjord' ? .62 : coast === 'archipelago' ? .7 : .48
  const base = fbm(record.seed, x * k + 7, y * k + 7, z * k + 7, coast === 'smooth' ? 3 : 5, detail)
  return clamp01(.5 + (base - .5) * (1 + relief * 1.6))
}

/** The height the sea stands at (the design's isLand threshold). */
export const seaHeight = (record: WorldBodyRecord): number => .28 + record.landmass.sea_level * .44
export const isLand = (record: WorldBodyRecord, height: number): boolean => height > seaHeight(record)

// ── the shore ─────────────────────────────────────────────────────────────────────────────────────────────────────────

/** Where a location is drawn on this body: its own point where that is land, else the nearest shore found within 20° (rings of
 * 2°, every 30°, the design's drawnAt), said so. The location's coordinate is never changed: this is drawing only (placeTool.ts:
 * the atlas never writes a coordinate). `found` is false where no land stands within 20°: the location is then drawn at its own
 * point, on the sea, and still said to be off its shore. */
export function shoreOf(record: WorldBodyRecord, lat: number, lon: number): {lat: number; lon: number; shore: boolean; found: boolean} {
  const here = unitOf(lat, lon)
  if (isLand(record, heightAt(record, here.x, here.y, here.z))) return {lat, lon, shore: false, found: true}
  for (let r = 2; r <= 20; r += 2) {
    for (let a = 0; a < 360; a += 30) {
      const la = Math.max(-89, Math.min(89, lat + r * Math.sin(a * D2R))), lo = lon + r * Math.cos(a * D2R), q = unitOf(la, lo)
      if (isLand(record, heightAt(record, q.x, q.y, q.z))) return {lat: la, lon: ((lo + 540) % 360) - 180, shore: true, found: true}
    }
  }
  return {lat, lon, shore: true, found: false}
}

// ── the texture ───────────────────────────────────────────────────────────────────────────────────────────────────────

/** An equirect RGBA image in the Earth imagery's convention: row 0 is the north pole's edge (lat +90), column 0 is longitude −180,
 * the last column just short of +180. */
export interface BodyImage {
  readonly width: number
  readonly height: number
  readonly data: Uint8ClampedArray
}

// The cues EARTH_FRAG reads (shaders.ts EARTH_COMMON): sea is strongly blue against red (waterOf takes (b − r)/(b + .05) above .56),
// deep sea dark and the shelf light (shelf = smoothstep(.05, .3, luma)); land's tone is its luma, relief shading baked in, with
// chroma that keeps wet, dry and rock apart; ice and snow are white, never blue against red.
const DEEP = [0.012, 0.035, 0.13], SHELF = [0.07, 0.33, 0.56]
const WET = [0.16, 0.3, 0.1], DRY = [0.55, 0.45, 0.27], ROCK = [0.46, 0.42, 0.38], ICE = [0.9, 0.92, 0.93]
const smooth = (e0: number, e1: number, x: number) => { const t = clamp01((x - e0) / (e1 - e0)); return t * t * (3 - 2 * t) }
const byte = (x: number) => Math.round(clamp01(x) * 255)

/** The body as an equirect image, `width` × `width / 2`. Deterministic: the same record and width give the same bytes. */
export function bodyImage(record: WorldBodyRecord, width = 1024): BodyImage {
  const w = Math.max(8, Math.floor(width / 2) * 2), h = w / 2
  // the sphere's points by column and row, once: x = cos(lat)·cos(lon), y = sin(lat), z = cos(lat)·sin(lon) (unitOf)
  const cosLon = new Float64Array(w), sinLon = new Float64Array(w), cosLat = new Float64Array(h), sinLat = new Float64Array(h)
  for (let i = 0; i < w; i++) { const lon = (-180 + (i + .5) * 360 / w) * D2R; cosLon[i] = Math.cos(lon); sinLon[i] = Math.sin(lon) }
  for (let j = 0; j < h; j++) { const lat = (90 - (j + .5) * 180 / h) * D2R; cosLat[j] = Math.cos(lat); sinLat[j] = Math.sin(lat) }
  const heights = new Float32Array(w * h)
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) heights[j * w + i] = heightAt(record, cosLat[j] * cosLon[i], sinLat[j], cosLat[j] * sinLon[i])
  const sea = seaHeight(record), {relief} = record.landmass, {warmth, moisture, ice_caps} = record.climate
  const polar = 1 - ice_caps * .45, lift = 6 + relief * 18
  const data = new Uint8ClampedArray(w * h * 4)
  for (let j = 0; j < h; j++) {
    const coslat = Math.max(cosLat[j], .05), ice = Math.abs(sinLat[j]) > polar
    for (let i = 0; i < w; i++) {
      const at = j * w + i, height = heights[at]
      let r: number, g: number, b: number
      if (height <= sea) {
        // the sea: dark in the deep, lifting to the shelf as it nears the coast
        const k = smooth(sea - .14, sea, height)
        r = DEEP[0] + (SHELF[0] - DEEP[0]) * k; g = DEEP[1] + (SHELF[1] - DEEP[1]) * k; b = DEEP[2] + (SHELF[2] - DEEP[2]) * k
      } else {
        // the land: wet or dry by the climate (the design's `wet`), rock with height, its relief shaded from the north-west
        const x = cosLat[j] * cosLon[i], y = sinLat[j], z = cosLat[j] * sinLon[i]
        const wet = smooth(.35, .65, clamp01(moisture * 1.2 - (warmth - .5) * .6 + (fbm(record.seed + 9, x * 3, y * 3, z * 3, 2, .5) - .5)))
        const above = (height - sea) / Math.max(1 - sea, .05), rock = smooth(.45, .9, above)
        const east = heights[j * w + ((i + 1) % w)], west = heights[j * w + ((i + w - 1) % w)]
        const north = heights[Math.max(0, j - 1) * w + i], south = heights[Math.min(h - 1, j + 1) * w + i]
        const shade = Math.max(.35, Math.min(1.35, 1 + (north - south - (east - west) / coslat) * lift)) * (.75 + .35 * above)
        r = (DRY[0] + (WET[0] - DRY[0]) * wet) * (1 - rock) + ROCK[0] * rock
        g = (DRY[1] + (WET[1] - DRY[1]) * wet) * (1 - rock) + ROCK[1] * rock
        b = (DRY[2] + (WET[2] - DRY[2]) * wet) * (1 - rock) + ROCK[2] * rock
        r *= shade; g *= shade; b *= shade
      }
      // the ice caps (the design's polar test: |y| above 1 − ice × .45)
      if (ice) {
        const k = height <= sea ? .85 : .95
        r += (ICE[0] - r) * k; g += (ICE[1] - g) * k; b += (ICE[2] - b) * k
      }
      data[at * 4] = byte(r)
      data[at * 4 + 1] = byte(g)
      data[at * 4 + 2] = byte(b)
      data[at * 4 + 3] = 255
    }
  }
  return {width: w, height: h, data}
}

/** How much of the body is land, 0–1, on the image's own cells weighted by their area (a reading for the device, not a setting). */
export function landShare(record: WorldBodyRecord, width = 128): number {
  const w = Math.max(8, Math.floor(width / 2) * 2), h = w / 2, sea = seaHeight(record)
  let land = 0, all = 0
  for (let j = 0; j < h; j++) {
    const lat = 90 - (j + .5) * 180 / h, area = Math.cos(lat * D2R)
    for (let i = 0; i < w; i++) {
      const p = unitOf(lat, -180 + (i + .5) * 360 / w)
      if (heightAt(record, p.x, p.y, p.z) > sea) land += area
      all += area
    }
  }
  return land / all
}

// ── the reroll ────────────────────────────────────────────────────────────────────────────────────────────────────────

/** The seed a reroll asks the owner for: named from the record and the revision it was read at, so the same press on the same
 * reading asks for the same seed, and never the seed it already has. Nothing here is random. */
export function nextSeed(record: WorldBodyRecord, revision: number): number {
  let h = 0x811c9dc5
  const text = `${record.body_ref}|${record.seed}|${revision}`
  for (let i = 0; i < text.length; i++) { h ^= text.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0 }
  h ^= h >>> 16; h = Math.imul(h, 0x7feb352d) >>> 0; h ^= h >>> 15; h = Math.imul(h, 0x846ca68b) >>> 0; h ^= h >>> 16
  const seed = h >>> 0
  return seed === record.seed ? (seed + 1) >>> 0 : seed
}

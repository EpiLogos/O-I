/** Native IPC reaches only what the ACL admits: every command the host registers is in the build manifest and allowed by
 * a capability. A registered command missing from either is denied at runtime ("not allowed by ACL") while every scripted
 * test still passes — the continuity admission and the Factory working surface / decision confirmation were, until this. */
import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync, readdirSync} from 'node:fs';
import {rustCode, read} from './source.mjs';

const registered = () => [...rustCode(read('src-tauri/src/main.rs')).matchAll(/generate_handler!\s*\[([^\]]*)\]/g)]
  .flatMap(match => match[1].split(',').map(name => name.trim().split('::').pop()).filter(Boolean)).sort();
const manifest = () => {
  const build = read('src-tauri/build.rs');
  const list = build.slice(build.indexOf('.commands(&['), build.indexOf('])', build.indexOf('.commands(&[')));
  return [...list.matchAll(/"([a-z_]+)"/g)].map(match => match[1]).sort();
};
const capabilityDir = new URL('../../src-tauri/capabilities/', import.meta.url);
const allowed = () => new Set(readdirSync(capabilityDir).filter(file => file.endsWith('.json'))
  .flatMap(file => JSON.parse(readFileSync(new URL(file, capabilityDir), 'utf8')).permissions.filter(entry => typeof entry === 'string')));

test('every registered native command is in the build manifest, and the manifest names nothing unregistered', () => {
  assert.deepEqual(manifest(), registered());
});

test('every manifest command is allowed by a capability, and has its generated permission', () => {
  const permissions = allowed();
  const permissionDir = new URL('../../src-tauri/permissions/autogenerated/', import.meta.url);
  const generated = new Set(readdirSync(permissionDir).map(file => file.replace(/\.toml$/, '')));
  for (const command of manifest()) {
    assert.ok(permissions.has(`allow-${command.replaceAll('_', '-')}`), `${command} is allowed by no capability`);
    assert.ok(generated.has(command), `${command} has no generated permission (run cargo build in src-tauri)`);
  }
});

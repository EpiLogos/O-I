import assert from 'node:assert/strict';
import {createServer} from 'vite';
import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
const out=new URL('./agent-native-results/',import.meta.url);
await mkdir(out,{recursive:true});
const server=await createServer({server:{port:0,strictPort:false,host:'127.0.0.1'}});
let browser;
const evidence=[];
try {
 await server.listen();
 const address=server.httpServer.address();
 assert.equal(typeof address,'object');
 browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1100,height:850}});
 const errors=[];page.on('pageerror',error=>errors.push(String(error)));
 await page.goto(`http://127.0.0.1:${address.port}/tests/agent-native-browser.html`);
 // The model chip (10-SIDEBARS §4.1, A1): the session's real model, its
 // menu exactly the harness's advertised models; choosing one is the owner's
 // model-select bound to the read's native session.
 const chip=page.locator('button[data-chip="model"]');
 const items=page.locator('.chat-model-item');
 const openMenu=async()=>{if(await chip.getAttribute('aria-expanded')!=='true')await chip.click();await items.first().waitFor();};
 await chip.waitFor();
 await page.waitForFunction(()=>window.controlled.modelState().phase==='ready');
 assert.equal((await chip.innerText()).trim(),'Model A');
 await openMenu();
 assert.deepEqual((await items.allInnerTexts()).map(text=>text.trim()),['Model A','Model B']);
 assert.equal(await items.nth(0).getAttribute('aria-checked'),'true');
 assert.equal(await items.nth(1).isDisabled(),false);
 const draft=await page.getByRole('textbox',{name:'Message',exact:true}).inputValue();
 await items.nth(1).click();
 await page.waitForFunction(()=>document.querySelector('button[data-chip="model"]')?.textContent?.trim()==='Model B');
 await openMenu();
 await page.getByText('Set for this session. No model turn has run on it yet.',{exact:true}).waitFor();
 assert.equal(await page.getByRole('textbox',{name:'Message',exact:true}).inputValue(),draft);
 const written=await page.evaluate(()=>window.controlled.calls.filter(call=>call.action==='model-select'));
 assert.equal(written.length,1);assert.equal(written[0].expected_native_session_id,'native-browser');assert.equal(written[0].provider_model_id,'test/b');
 evidence.push('The model chip lists the native choices, confirms a selection and preserves the draft.');
 await page.evaluate(()=>window.controlled.loseAck());
 await items.nth(0).click();
 await openMenu();
 await page.getByRole('alert').filter({hasText:'outcome is unconfirmed'}).waitFor();
 assert.equal(await items.nth(0).isDisabled(),true);assert.equal(await items.nth(1).isDisabled(),true);
 assert.equal(await chip.getAttribute('data-marked'),'true');
 assert.equal(await page.evaluate(()=>window.controlled.calls.filter(call=>call.action==='model-select').length),2);
 evidence.push('Lost native acknowledgement becomes unknown; no automatic replay is sent.');
 await page.getByRole('menuitem',{name:'Read the session again',exact:true}).click();
 await page.waitForFunction(()=>window.controlled.modelState().phase==='ready');
 assert.equal((await chip.innerText()).trim(),'Model A');
 await page.evaluate(()=>window.controlled.readonly());
 await openMenu();
 await page.getByText('This harness has launch-time selection only.',{exact:true}).waitFor();
 assert.equal(await items.nth(1).isDisabled(),true);
 evidence.push('A harness-native read-only selector remains disabled without inventing a universal model roster.');
 await page.keyboard.press('Escape');
 await page.evaluate(()=>window.controlled.disconnect());
 await page.locator('.chat-composer[data-connection="disconnected"]').waitFor();
 await page.getByText('Connection FutureUnknownState',{exact:true}).waitFor();
 assert.equal(await page.getByRole('textbox',{name:'Message',exact:true}).inputValue(),draft);
 evidence.push('Unknown connection states never become a green connected badge; draft survives the fault.');
 assert.deepEqual(errors,[]);
 await page.screenshot({path:new URL('composer.png',out).pathname,fullPage:true});
 await writeFile(new URL('receipt.json',out),JSON.stringify({kind:'controlled-browser-not-live-model',checks:evidence},null,2));
 console.log(JSON.stringify({passed:evidence.length,checks:evidence},null,2));
}finally{await browser?.close();await server.close();}

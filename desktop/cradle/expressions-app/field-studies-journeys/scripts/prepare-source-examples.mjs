// Prepares embedded source-study assets: base64 data URLs for the two mask
// images, the twelve-face series, and the ASCII transcription. Run after
// replacing files in sources/.
import {readFileSync, writeFileSync, readdirSync} from 'node:fs';

const sources = new URL('../sources/', import.meta.url);
const out = new URL('../src/sourceExamplesData.generated.ts', import.meta.url);

const dataUrl = (file, mime) => `data:${mime};base64,${readFileSync(new URL(file, sources)).toString('base64')}`;
const ascii = readFileSync(new URL('face-ascii.txt', sources), 'utf8');

// The series opens with the original mono mask, then the eleven JPEG
// variations in emotional arc order (see sources/faces/).
const faceFiles = readdirSync(new URL('faces/', sources)).filter(f => /^face-\d+\.jpg$/.test(f)).sort();
const faces = [dataUrl('face-mono.png', 'image/png'), ...faceFiles.map(f => dataUrl('faces/' + f, 'image/jpeg'))];

const generated = `// Generated by field-studies-journeys/scripts/prepare-source-examples.mjs.
// Source assets live in field-studies-journeys/sources/. Do not edit by hand.

export const FACE_COLOUR_DATA_URL = ${JSON.stringify(dataUrl('face-colour.jpg', 'image/jpeg'))};

export const FACE_MONO_DATA_URL = ${JSON.stringify(dataUrl('face-mono.png', 'image/png'))};

export const FACE_ASCII_ART = ${JSON.stringify(ascii)};

/** Twelve masks in series order: slot 0 is the original mono mask. */
export const FACES_DATA_URLS: string[] = ${JSON.stringify(faces)};
`;

writeFileSync(out, generated);
console.log(`sourceExamplesData.generated.ts written (${Math.round(generated.length / 1024)} KiB, ${faces.length} faces)`);
